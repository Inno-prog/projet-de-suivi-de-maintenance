
package com.dgsi.maintenance.controller;

import java.util.List;
import java.util.Map;

import com.dgsi.maintenance.service.KeycloakService;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/keycloak")
@CrossOrigin(origins = "*", maxAge = 3600)
public class KeycloakController {

    @Autowired
    private KeycloakService keycloakService;

    /**
     * Récupère tous les prestataires depuis Keycloak
     */
    @GetMapping("/prestataires")
    public ResponseEntity<List<Map<String, Object>>> getPrestatairesFromKeycloak() {
        try {
            List<Map<String, Object>> prestataires = keycloakService.getAllPrestataires();
            return ResponseEntity.ok(prestataires);
        } catch (Exception e) {
            System.err.println("Erreur lors de la récupération des prestataires depuis Keycloak: " + e.getMessage());
            e.printStackTrace();
            return ResponseEntity.internalServerError().build();
        }
    }

    /**
     * Récupère tous les utilisateurs depuis Keycloak
     */
    @GetMapping("/users")
    public ResponseEntity<List<Map<String, Object>>> getUsersFromKeycloak() {
        try {
            List<Map<String, Object>> users = keycloakService.getAllUsers();
            return ResponseEntity.ok(users);
        } catch (Exception e) {
            System.err.println("Erreur lors de la récupération des utilisateurs depuis Keycloak: " + e.getMessage());
            e.printStackTrace();
            return ResponseEntity.internalServerError().build();
        }
    }
}

