package com.dgsi.maintenance.controller;

import java.io.IOException;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import com.dgsi.maintenance.dto.RegisterRequest;
import com.dgsi.maintenance.entity.User;
import com.dgsi.maintenance.service.KeycloakService;
import com.dgsi.maintenance.service.UserService;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import jakarta.servlet.http.HttpServletResponse;
import jakarta.validation.Valid;

@RestController
@RequestMapping("/api/auth")
@CrossOrigin(origins = "*", maxAge = 3600)
public class AuthController {

    @Autowired
    private KeycloakService keycloakService;

    @Autowired
    private UserService userService;

    /**
     * Redirige vers la page d'inscription Keycloak
     * Après inscription, Keycloak redirigera vers la page de confirmation
     */
    @GetMapping("/register/redirect")
    public void redirectToKeycloakRegistration(HttpServletResponse response) throws IOException {
        String keycloakIssuer = "http://localhost:8080/realms/Maintenance-DGSI";
        String clientId = "maintenance-app";
        // Redirect to static HTML page
        String redirectUri = URLEncoder.encode("http://localhost:4200/registration-success.html", StandardCharsets.UTF_8.toString());

        String registrationUrl = keycloakIssuer + "/protocol/openid-connect/registrations?" +
                "client_id=" + clientId + "&" +
                "redirect_uri=" + redirectUri + "&" +
                "response_type=code&" +
                "scope=openid";

        response.sendRedirect(registrationUrl);
    }


    @PostMapping("/register")
    public ResponseEntity<?> register(@Valid @RequestBody RegisterRequest registerRequest) {
        try {
            // Vérifier si l'utilisateur existe déjà dans la base de données
            if (userService.existsByEmail(registerRequest.getEmail())) {
                return ResponseEntity.badRequest().body("Cet email est déjà utilisé");
            }

            // Créer l'utilisateur dans Keycloak
            String firstName = registerRequest.getNom().split(" ")[0];
            String lastName = registerRequest.getNom().substring(firstName.length()).trim();
            String userId = keycloakService.createUser(
                registerRequest.getEmail(), // Utiliser email comme username
                registerRequest.getEmail(),
                firstName,
                lastName,
                registerRequest.getPassword(),
                registerRequest.getRole()
            );

            // Créer l'utilisateur dans la base de données
            User user = userService.createUser(registerRequest);

            return ResponseEntity.ok().body("Inscription réussie. Veuillez vous connecter.");
        } catch (Exception e) {
            e.printStackTrace();
            return ResponseEntity.badRequest().body(e.getMessage());
        }
    }

    @PostMapping("/logout")
    public ResponseEntity<?> logout(@RequestParam(required = false) String refreshToken) {
        try {
            // Ici, vous pourriez invalider le refresh token côté serveur
            // Pour l'instant, on retourne simplement un succès
            return ResponseEntity.ok().body("Déconnexion réussie");
        } catch (Exception e) {
            e.printStackTrace();
            return ResponseEntity.internalServerError().build();
        }
    }
}

